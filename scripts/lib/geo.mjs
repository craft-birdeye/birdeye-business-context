export function zipMatchesState(zip, state) {
  const s = STATES[state];
  if (!s || !/^\d{5}$/.test(zip)) return false;
  const p = Number(zip.slice(0, 3));
  return s.zip.some(([lo, hi]) => p >= lo && p <= hi);
}
